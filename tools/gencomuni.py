# Generate comuni.h from the tables of the Anagrafe Nazionale (ANPR):
# all the Italian municipalities, the current and the ceased ones, as
# people born in a municipality which was later merged keep its code,
# plus the foreign countries under the "EE" province.
#
# Usage: tools/gencomuni.py > comuni.h

import csv
import io
import re
import sys
import unicodedata
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

BASE = 'https://www.anagrafenazionale.interno.it/wp-content/uploads/'
COMUNI = BASE + 'ANPR_archivio_comuni.csv'
STATI = BASE + 'tabella_2_statiesteri.xlsx'

# provinces which were only renamed, list their ceased municipalities under the new name
RENAMED = {'FO': 'FC', 'PS': 'PU'}


def download(url):
	req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
	with urllib.request.urlopen(req) as f:
		return f.read()


def comuni():
	rows = list(csv.DictReader(io.StringIO(download(COMUNI).decode('utf-8'))))
	# a few historical records have no cadastral code ("ND"), so no fiscal code
	rows = [r for r in rows if re.fullmatch('[A-Z][0-9]{3}', r['CODCATASTALE'])]
	active = {r['CODCATASTALE']: r for r in rows if r['STATO'] == 'A'}
	# for the ceased ones, the last record has the last name and province
	ceased = {}
	for r in rows:
		code = r['CODCATASTALE']
		if code not in active and (code not in ceased or r['DATACESSAZIONE'] > ceased[code]['DATACESSAZIONE']):
			ceased[code] = r
	for code, r in active.items():
		yield r['SIGLAPROVINCIA'], r['DENOMINAZIONE_IT'], code
	for code, r in ceased.items():
		prov = RENAMED.get(r['SIGLAPROVINCIA'], r['SIGLAPROVINCIA'])
		yield prov, '%s (fino al %s)' % (r['DENOMINAZIONE_IT'], r['DATACESSAZIONE'][:4]), code


def stati():
	z = zipfile.ZipFile(io.BytesIO(download(STATI)))
	ns = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
	shared = [''.join(t.text or '' for t in si.iter(ns + 't'))
		for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(ns + 'si')]

	def column(ref):
		n = 0
		for ch in re.match('[A-Z]+', ref).group(0):
			n = n * 26 + ord(ch) - ord('A') + 1
		return n - 1

	table = []
	for row in ET.fromstring(z.read('xl/worksheets/sheet1.xml')).iter(ns + 'row'):
		# empty cells are omitted, place the others by their reference
		cells = {}
		for c in row.findall(ns + 'c'):
			v = c.find(ns + 'v')
			text = '' if v is None else v.text
			cells[column(c.get('r'))] = shared[int(text)] if c.get('t') == 's' and text else text
		table.append(cells)
	header = {name: i for i, name in table[0].items()}
	for cells in table[1:]:
		get = lambda name: (cells.get(header[name]) or '').strip()
		if get('NASCITA') == 'S' and get('CODAT'):
			yield 'EE', get('DENOMINAZIONE'), get('CODAT')


def sortkey(record):
	prov, name, code = record
	plain = unicodedata.normalize('NFD', name)
	return prov, ''.join(c for c in plain if not unicodedata.combining(c)), name


def main():
	records = sorted(list(comuni()) + list(stati()), key=sortkey)
	seen = set()
	for prov, name, code in records:
		assert re.fullmatch('[A-Z]{2}', prov), (prov, name)
		assert re.fullmatch('[A-Z][0-9]{3}', code), (name, code)
		assert (prov, name) not in seen, (prov, name)
		seen.add((prov, name))

	out = sys.stdout
	out.write('// Generated by tools/gencomuni.py from the tables of the Anagrafe Nazionale:\n')
	out.write('// %s\n// %s\n\n' % (COMUNI, STATI))
	out.write('struct record {\n\tconst char prov[3];\n\tconst char *comune;\n\tconst char codice[5];\n};\n\n')
	out.write('const struct record comuni[] = {\n')
	out.write(',\n'.join('{"%s", "%s", "%s"}' % (p, n.replace('\\', '\\\\').replace('"', '\\"'), c)
		for p, n, c in records))
	out.write('};\n\nconst int comuni_length = %d;\n' % len(records))


if __name__ == '__main__':
	main()
